#!/usr/bin/env node
// Writes resources/licenses/THIRD_PARTY_NOTICES.md: the licence text of every package in the
// production dependency tree, read from node_modules. Run after changing dependencies:
//
//   bun run notices
//
// Packages limited to one OS or CPU (prebuilt binaries such as esbuild's) are left out so the
// output is the same on every machine. Packages without a licence file are listed with the
// licence named in their package.json.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'resources/licenses/THIRD_PARTY_NOTICES.md');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

function findPackageJson(name, fromDir) {
  for (let dir = fromDir; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name, 'package.json');
    if (fs.existsSync(candidate)) return fs.realpathSync(candidate);
    if (path.dirname(dir) === dir) return null;
  }
}

function licenseName(json) {
  if (typeof json.license === 'string') return json.license;
  if (json.license?.type) return json.license.type;
  if (Array.isArray(json.licenses)) return json.licenses.map((l) => l.type ?? l).join(' OR ');
  return 'UNKNOWN';
}

function licenseText(dir) {
  const files = fs
    .readdirSync(dir)
    .filter((f) => /^(licen[sc]e|copying|notice)(\..*)?$/i.test(f))
    .sort();
  return files.map((f) => fs.readFileSync(path.join(dir, f), 'utf8').trim()).join('\n\n');
}

const packages = new Map();
function walk(name, fromDir) {
  const file = findPackageJson(name, fromDir);
  if (!file) return; // optional dependency not installed on this platform
  const json = JSON.parse(fs.readFileSync(file, 'utf8'));
  const id = `${json.name}@${json.version}`;
  if (packages.has(id)) return;
  const dir = path.dirname(file);
  const platformOnly = Boolean(json.os || json.cpu);
  packages.set(id, platformOnly ? null : { id, license: licenseName(json), text: licenseText(dir) });
  for (const dep of Object.keys({ ...json.dependencies, ...json.optionalDependencies })) walk(dep, dir);
}
for (const dep of Object.keys(pkg.dependencies ?? {})) walk(dep, root);

const groups = new Map();
for (const entry of packages.values()) {
  if (!entry) continue;
  const key = entry.text || `(no licence file; package.json says ${entry.license})`;
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(entry);
}

const sections = [...groups.entries()]
  .map(([text, entries]) => ({ text, entries: entries.sort((a, b) => a.id.localeCompare(b.id)) }))
  .sort((a, b) => a.entries[0].id.localeCompare(b.entries[0].id));

const count = sections.reduce((n, s) => n + s.entries.length, 0);
let out = `# Third-party notices\n\nBoundary includes the following ${count} npm packages. Generated by\n\`scripts/generate-third-party-notices.mjs\`; do not edit by hand.\n`;
for (const { text, entries } of sections) {
  out += `\n---\n\n${entries.map((e) => `- ${e.id} (${e.license})`).join('\n')}\n\n\`\`\`text\n${text}\n\`\`\`\n`;
}
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out);
console.log(`Wrote ${path.relative(root, outFile)}: ${count} packages in ${sections.length} licence groups`);
